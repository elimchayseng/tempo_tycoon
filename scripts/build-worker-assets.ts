/**
 * Embed the Vite build (dist/) into the Worker bundle.
 *
 * Writes worker/static-manifest.generated.js — a map of URL path →
 * { type, body (base64) } that worker/static.ts serves. Run after `vite build`
 * and before `wrangler deploy` (npm run cf:deploy does both).
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "fs";
import { join, relative, extname, dirname } from "path";
import { fileURLToPath } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const distDir = join(root, "dist");
const outFile = join(root, "worker", "static-manifest.generated.js");

const CONTENT_TYPES: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
  ".ico": "image/x-icon",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".txt": "text/plain; charset=utf-8",
};

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const files = walk(distDir);
if (!files.some((f) => relative(distDir, f) === "index.html")) {
  throw new Error("dist/index.html not found — run `vite build` first");
}

const entries: Record<string, { type: string; body: string }> = {};
let totalBytes = 0;
for (const file of files) {
  const urlPath = "/" + relative(distDir, file).split("\\").join("/");
  const data = readFileSync(file);
  totalBytes += data.length;
  entries[urlPath] = {
    type: CONTENT_TYPES[extname(file).toLowerCase()] ?? "application/octet-stream",
    body: data.toString("base64"),
  };
}

writeFileSync(
  outFile,
  "// Generated by scripts/build-worker-assets.ts — do not edit.\n" +
    `export default ${JSON.stringify(entries)};\n`,
);

console.log(`Embedded ${files.length} files (${(totalBytes / 1024).toFixed(1)} KiB) into ${relative(root, outFile)}`);
